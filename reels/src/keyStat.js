// 오리 기자 "오늘의 숫자" 추출기 — title/summary 문자열에 실제로 있는 핵심 수치만 뽑는다(값을 만들지 않는다).
// 정밀도를 재현율보다 우선한다: 확신이 없으면 kicker로 폴백하고 isStat=false를 돌려준다.
// (2026-10-05: 구 추출기가 "제미나이 4 아르곤"에서 "4 아르", 날짜에서 "10월"을 뽑던 버그의 root cause 수정)

// 수사 — 앞 글자가 숫자·소수점·쉼표·영문·하이픈·물결·"제"·조/억/만이면 다른 토큰의 일부("GPT-4", "Opus5", "23~24",
// "제3회", "1조 5000억"의 "5000억")라 받지 않는다.
// 뒤에 조/억/만 + 숫자가 이어지는 복합 수사("26만8000", "3조 5000억")를 허용한다. 공백 뒤 숫자는 그 뒤에 다시
// 조/억/만이 올 때만 잇는다("100만 2주", "1조 3개"를 한 값으로 붙이지 않게).
const NUM =
  '(?<![\\d.,A-Za-z\\-~～제])(?<![조억만]\\s?)(?:\\d{1,3}(?:,\\d{3})+(?:\\.\\d+)?|\\d+(?:\\.\\d+)?)(?:(?:조|억|만)(?:\\d+|\\s+\\d+(?=조|억|만)))*';
// 뒤쪽 경계 — 문자열 끝, 공백, 구두점, 조사("으로"·"부터"·"까지" 포함)일 때만 받는다("31개국", "5개사", "2조각" 제외).
// 모든 패턴에 건다.
const END = '(?=$|[\\s.,!?·…:;/)\\]"\'”’》」]|[로를을이가은는의에와과도만씩]|으로|부터|까지)';

const PATTERNS = [
  // 1. 퍼센트(퍼센트포인트 포함)
  new RegExp(`${NUM}%p?${END}`),
  // 2. 수량 복합 — 금액보다 먼저 시도한다("100만 토큰", "300만 명"이 "100만"·"300만"으로 잘리지 않게).
  new RegExp(`${NUM}(?:조|억|만)\\s*(?:명|건|개|대|토큰)${END}`),
  // 3. 금액·복합 — 뒤에 숫자나 수량 단위가 이어지면 받지 않는다("26만8000개"가 "26만"으로 잘리지 않게).
  new RegExp(`${NUM}(?:조|억|만)(?:\\s*(?:원|달러|유로|위안|엔))?${END}(?!\\s*(?:\\d|명|건|개|대|토큰))`),
  // 4. 배수
  new RegExp(`${NUM}배${END}`),
  // 5. 기간 — 연도("2027년")는 1~2자리만, 날짜("15일 발효", "10월 2일")는 기간 표현이 뒤따를 때만 받는다.
  //    "간"은 붙여 쓰고 뒤에 경계가 올 때만("20일간"은 받고 "15일 간담회"는 뺀다).
  new RegExp(`${NUM}(?:개월|시간|주)${END}`),
  new RegExp(`(?<![\\d.,A-Za-z\\-~～제])(?<![조억만]\\s?)\\d{1,2}년${END}`),
  new RegExp(`(?<!월\\s*)${NUM}일(?=간${END}|\\s*(?:만에|동안|연장|이내))`),
  // 6. 수량 단일 — 숫자와 단위 사이 공백 없음("Opus 5 대비" 제외). "위"(순위)·"대"("3대 분야")는 정밀도 우선으로 뺐다.
  new RegExp(`${NUM}(?:명|건|개|곳|종|회|달러|원)${END}`),
];

// 반환: {text, isStat}. 같은 패턴 안에서는 title을 먼저, 그다음 summary의 첫 등장을 본다.
export const extractKeyStat = (issue) => {
  const fields = [issue.title ?? '', issue.summary ?? ''];
  for (const pattern of PATTERNS) {
    for (const field of fields) {
      const m = pattern.exec(field);
      if (m) return {text: m[0], isStat: true};
    }
  }
  return {text: issue.kicker, isStat: false};
};
